# 4. Caja Chica
# --------------------------------------------------------------------------- #
def _caja_chica_section(ctx: dict) -> None:
    st.subheader("💼 Caja Chica")
    st.caption(
        "La Caja Chica es un fondo fijo. **No se considera ingreso** y se muestra "
        "por separado en el Balance Financiero."
    )

    sede_opts = [config.SEDE_PRINCIPAL, config.SEDE_SUCURSAL]
    sede_sel = st.selectbox("Sede", sede_opts, key="cfg_cc_sede")

    if ctx["editable"]:
        with st.expander("➕ Registrar revisión de Caja Chica"):
            with st.form("cfg_caja_chica_form", clear_on_submit=True):
                c1, c2 = st.columns(2)
                with c1:
                    cc_fecha = st.date_input("Fecha", value=date.today(), key="cfg_cc_fecha")
                    cc_base = st.number_input(
                        "Monto base (fondo fijo)", min_value=0.0, step=10.0, key="cfg_cc_base"
                    )
                with c2:
                    cc_contado = st.number_input(
                        "Dinero contado", min_value=0.0, step=10.0, key="cfg_cc_contado"
                    )
                    cc_diferencia = cc_contado - cc_base
                    st.metric("Diferencia", f"$ {cc_diferencia:,.2f}")
                cc_obs = st.text_area("Observación", key="cfg_cc_obs")
                cc_sub = st.form_submit_button("Guardar registro")

            if cc_sub:
                try:
                    db.save_caja_chica(
                        fecha=cc_fecha,
                        sede=sede_sel,
                        monto_base=Decimal(str(cc_base)),
                        dinero_contado=Decimal(str(cc_contado)),
                        observaciones=cc_obs.strip() or None,
                        usuario_rol=ctx["usuario_rol"],
                    )
                    db.log_audit(
                        db.AUDIT_CONFIG,
                        "Configuración",
                        detalle=f"Caja Chica registrada · {sede_sel} · diferencia ${cc_diferencia:,.2f}",
                        usuario_rol=ctx["usuario_rol"],
                        sede=sede_sel,
                    )
                except Exception as exc:  # noqa: BLE001
                    st.error(f"No se pudo guardar: {exc}")
                else:
                    st.success("Registro de Caja Chica guardado.")
                    st.rerun()

    # History
    today = date.today()
    month_start = today.replace(day=1)
    c1, c2 = st.columns(2)
    with c1:
        cc_from = st.date_input("Desde", value=month_start, key="cfg_cc_from")
    with c2:
        cc_to = st.date_input("Hasta", value=today, key="cfg_cc_to")

    registros = db.list_caja_chica(sede=sede_sel, date_from=cc_from, date_to=cc_to)
    if not registros:
        st.info("No hay registros de Caja Chica para el filtro seleccionado.")
        return

    rows = [
        {
            "Fecha": r["fecha"].strftime("%Y-%m-%d"),
            "Sede": r["sede"],
            "Monto base": _money(r["monto_base"]),
            "Contado": _money(r["dinero_contado"]),
            "Diferencia": _money(r["diferencia"]),
            "Observación": r["observaciones"] or "—",
            "Registrado por": r["usuario_rol"] or "—",
        }
        for r in registros
    ]
    st.dataframe(rows, use_container_width=True, hide_index=True)


