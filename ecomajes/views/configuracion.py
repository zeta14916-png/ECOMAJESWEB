# 6. Copias de seguridad
# --------------------------------------------------------------------------- #
def _backups_section() -> None:
    st.subheader("🗄️ Copias de Seguridad")
    st.caption(
        "Las copias de seguridad se generan automáticamente antes de cada importación de productos. "
        "**No se borran datos ni se exponen credenciales.**"
    )

    import psycopg2.extras as _extras

    with db._get_conn() as conn:
        with conn.cursor(cursor_factory=_extras.RealDictCursor) as cur:
            cur.execute(
                "SELECT id, created_at, import_mode, product_count, restored_at "
                "FROM product_backups ORDER BY created_at DESC LIMIT 50"
            )
            backups = [dict(r) for r in cur.fetchall()]

    if not backups:
        st.info("No hay copias de seguridad registradas todavía.")
        return

    rows = [
        {
            "ID": b["id"],
            "Fecha": b["created_at"].strftime("%Y-%m-%d %H:%M"),
            "Modo": b["import_mode"],
            "Productos": b["product_count"],
            "Restaurado en": b["restored_at"].strftime("%Y-%m-%d %H:%M")
            if b["restored_at"]
            else "—",
        }
        for b in backups
    ]
    st.dataframe(rows, use_container_width=True, hide_index=True)
    st.caption(
        "Para restaurar una copia, use la opción de restauración en el módulo de importación."
    )


# --------------------------------------------------------------------------- #
# Entry point
# --------------------------------------------------------------------------- #
def render(ctx: dict) -> None:
    st.header(ctx["title"])
    st.caption(ctx["breadcrumb"])

    tabs = st.tabs([
        "🏢 Empresa",
        "👤 Usuarios",
        "🔐 Roles y Permisos",
        "💼 Caja Chica",
        "⚙️ Parámetros",
        "🗄️ Copias de Seguridad",
    ])

    with tabs[0]:
        _empresa_section(ctx)

    with tabs[1]:
        _usuarios_section(ctx)

    with tabs[2]:
        _roles_section()

    with tabs[3]:
        _caja_chica_section(ctx)

    with tabs[4]:
        _parametros_section(ctx)

    with tabs[5]:
        _backups_section()
