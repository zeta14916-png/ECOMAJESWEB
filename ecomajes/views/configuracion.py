"""Configuración view for ECOMAJES ERP (GERENCIA > Configuración).

Sections:
1. Datos de la Empresa   — nombre, RUC, dirección, teléfono, correo, sedes.
2. Usuarios              — view and manage employees/system users.
3. Roles y Permisos      — read-only display of role definitions.
4. Caja Chica            — register and review petty-cash balance checks.
5. Parámetros            — horarios laborales, límites de stock, otros.
6. Copias de Seguridad   — list of product_backups generated by importers.

Rules enforced:
- No se exponen contraseñas en texto visible.
- Área Administrativa no puede cambiar permisos gerenciales.
- Caja Chica no se considera ingreso; se muestra por separado.
- Toda modificación queda en audit_log con usuario y fecha.
"""

from datetime import date
from decimal import Decimal

import streamlit as st

from ecomajes import config, db


def _money(v) -> float:
    return float(v) if v is not None else 0.0


# --------------------------------------------------------------------------- #
# 1. Datos de la Empresa
# --------------------------------------------------------------------------- #
def _empresa_section(ctx: dict) -> None:
    st.subheader("🏢 Datos de la Empresa")
    current = db.get_empresa_config()

    with st.form("empresa_config_form"):
        col1, col2 = st.columns(2)
        with col1:
            nombre = st.text_input("Nombre de la empresa", value=current.get("nombre", ""))
            ruc = st.text_input("RUC", value=current.get("ruc", ""))
            direccion = st.text_input("Dirección", value=current.get("direccion", ""))
        with col2:
            telefono = st.text_input("Teléfono", value=current.get("telefono", ""))
            correo = st.text_input("Correo electrónico", value=current.get("correo", ""))

        st.markdown("**Nombres de sedes**")
        col3, col4 = st.columns(2)
        with col3:
            sede_principal = st.text_input(
                "Sede Principal", value=current.get("sede_principal", "Sede Principal")
            )
        with col4:
            sede_sucursal = st.text_input(
                "Sucursal", value=current.get("sede_sucursal", "Sucursal")
            )

        submitted = st.form_submit_button("💾 Guardar datos de empresa")

    if submitted:
        if not nombre.strip():
            st.error("El nombre de la empresa es obligatorio.")
            return
        try:
            db.save_empresa_config(
                {
                    "nombre": nombre.strip(),
                    "ruc": ruc.strip(),
                    "direccion": direccion.strip(),
                    "telefono": telefono.strip(),
                    "correo": correo.strip(),
                    "sede_principal": sede_principal.strip() or "Sede Principal",
                    "sede_sucursal": sede_sucursal.strip() or "Sucursal",
                },
                usuario_rol=ctx["usuario_rol"],
            )
            db.log_audit(
                db.AUDIT_CONFIG,
                "Configuración",
                detalle="Datos de empresa actualizados",
                usuario_rol=ctx["usuario_rol"],
            )
        except Exception as exc:  # noqa: BLE001
            st.error(f"No se pudo guardar: {exc}")
        else:
            st.success("Datos de empresa guardados correctamente.")
            st.rerun()


# --------------------------------------------------------------------------- #
# 2. Usuarios
# --------------------------------------------------------------------------- #
def _usuarios_section(ctx: dict) -> None:
    st.subheader("👤 Usuarios")

    col_search, col_sede = st.columns(2)
    with col_search:
        search = st.text_input("🔍 Buscar usuario", key="cfg_user_search")
    with col_sede:
        sede_opts = ["Todas"] + config.get_sedes(config.ROLE_GERENCIA)[:2]
        sede_filter = st.selectbox("Sede", sede_opts, key="cfg_user_sede")

    employees = db.list_employees(
        search=search.strip() or None,
        sede=None if sede_filter == "Todas" else sede_filter,
    )

    rows = [
        {
            "Nombre": e["nombre"],
            "Usuario": e["username"],
            "Documento": e.get("documento") or "—",
            "Cargo": e.get("cargo") or "—",
            "Rol": e["rol"],
            "Sede": e.get("sede") or "—",
            "Estado": db.EMPLOYEE_STATUS_LABELS.get(e["estado"], e["estado"]),
            "Fecha ingreso": (
                e["fecha_ingreso"].strftime("%Y-%m-%d") if e["fecha_ingreso"] else "—"
            ),
        }
        for e in employees
    ]
    if rows:
        st.dataframe(rows, use_container_width=True, hide_index=True)
        st.caption(f"{len(rows)} usuario(s) encontrado(s).")
    else:
        st.info("No hay usuarios registrados.")

    if ctx["editable"]:
        with st.expander("➕ Crear nuevo usuario"):
            with st.form("cfg_create_user", clear_on_submit=True):
                c1, c2 = st.columns(2)
                with c1:
                    u_nombre = st.text_input("Nombre completo")
                    u_username = st.text_input("Nombre de usuario")
                    u_password = st.text_input("Contraseña", type="password")
                    u_rol = st.selectbox("Rol", config.ROLES)
                with c2:
                    u_documento = st.text_input("Documento de identidad")
                    u_cargo = st.text_input("Cargo")
                    u_sede = st.selectbox(
                        "Sede", config.get_sedes(config.ROLE_GERENCIA)[:2]
                    )
                    u_salario = st.number_input("Salario", min_value=0.0, step=50.0)
                u_submitted = st.form_submit_button("Crear usuario")

            if u_submitted:
                if not u_nombre.strip() or not u_username.strip() or not u_password:
                    st.error("Nombre, usuario y contraseña son obligatorios.")
                else:
                    try:
                        db.create_employee(
                            nombre=u_nombre.strip(),
                            username=u_username.strip(),
                            password=u_password,
                            rol=u_rol,
                            documento=u_documento.strip() or None,
                            cargo=u_cargo.strip() or None,
                            sede=u_sede,
                            salario=Decimal(str(u_salario)),
                        )
                        db.log_audit(
                            db.AUDIT_CONFIG,
                            "Configuración",
                            detalle=f"Usuario creado: {u_username.strip()}",
                            usuario_rol=ctx["usuario_rol"],
                        )
                    except db.EmployeeError as exc:
                        st.error(str(exc))
                    except Exception as exc:  # noqa: BLE001
                        st.error(f"Error: {exc}")
                    else:
                        st.success(f"Usuario «{u_nombre.strip()}» creado.")
                        st.rerun()

        if employees:
            with st.expander("✏️ Editar / Activar / Desactivar usuario"):
                by_id = {e["id"]: e for e in employees}
                sel_id = st.selectbox(
                    "Seleccionar usuario",
                    list(by_id.keys()),
                    format_func=lambda i: f"{by_id[i]['nombre']} ({by_id[i]['username']})",
                    key="cfg_edit_user_select",
                )
                emp = by_id[sel_id]
                with st.form(f"cfg_edit_user_{sel_id}"):
                    c1, c2 = st.columns(2)
                    with c1:
                        e_nombre = st.text_input("Nombre", value=emp["nombre"])
                        e_username = st.text_input("Usuario", value=emp["username"])
                        e_password = st.text_input(
                            "Nueva contraseña (vacío = sin cambio)", type="password"
                        )
                        current_rol = (
                            emp["rol"] if emp["rol"] in config.ROLES else config.ROLES[0]
                        )
                        e_rol = st.selectbox(
                            "Rol", config.ROLES, index=config.ROLES.index(current_rol)
                        )
                    with c2:
                        e_doc = st.text_input("Documento", value=emp.get("documento") or "")
                        e_cargo = st.text_input("Cargo", value=emp.get("cargo") or "")
                        sede_opts2 = config.get_sedes(config.ROLE_GERENCIA)[:2]
                        e_sede = st.selectbox(
                            "Sede",
                            sede_opts2,
                            index=sede_opts2.index(emp["sede"])
                            if emp.get("sede") in sede_opts2
                            else 0,
                        )
                        e_salario = st.number_input(
                            "Salario",
                            min_value=0.0,
                            value=float(emp["salario"] or 0),
                            step=50.0,
                        )
                    e_estado = st.selectbox(
                        "Estado",
                        list(db.EMPLOYEE_STATUS_LABELS.keys()),
                        index=list(db.EMPLOYEE_STATUS_LABELS.keys()).index(emp["estado"])
                        if emp["estado"] in db.EMPLOYEE_STATUS_LABELS
                        else 0,
                        format_func=lambda k: db.EMPLOYEE_STATUS_LABELS[k],
                    )
                    e_submitted = st.form_submit_button("Guardar cambios")

                if e_submitted:
                    if not e_nombre.strip() or not e_username.strip():
                        st.error("Nombre y usuario son obligatorios.")
                    else:
                        try:
                            db.update_employee(
                                employee_id=sel_id,
                                nombre=e_nombre.strip(),
                                username=e_username.strip(),
                                rol=e_rol,
                                estado=e_estado,
                                telefono=emp.get("telefono"),
                                direccion=emp.get("direccion"),
                                fecha_ingreso=emp.get("fecha_ingreso"),
                                salario=Decimal(str(e_salario)),
                                password=e_password or None,
                                documento=e_doc.strip() or None,
                                cargo=e_cargo.strip() or None,
                                sede=e_sede,
                            )
                            db.log_audit(
                                db.AUDIT_CONFIG,
                                "Configuración",
                                detalle=f"Usuario editado: {e_username.strip()}",
                                usuario_rol=ctx["usuario_rol"],
                            )
                        except db.EmployeeError as exc:
                            st.error(str(exc))
                        except Exception as exc:  # noqa: BLE001
                            st.error(f"Error: {exc}")
                        else:
                            st.success("Usuario actualizado.")
                            st.rerun()


