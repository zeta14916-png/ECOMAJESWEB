# --------------------------------------------------------------------------- #
_PARAMS_CATALOG = [
    ("horario_entrada", "Hora de entrada (HH:MM)", "08:00"),
    ("horario_salida", "Hora de salida (HH:MM)", "18:00"),
    ("tolerancia_tardanza_min", "Tolerancia de tardanza (minutos)", "15"),
    ("stock_minimo_global", "Stock mínimo global (unidades)", "5"),
    ("moneda", "Moneda", "S/."),
    ("dias_laborales", "Días laborales (ej: Lun-Sab)", "Lunes-Sábado"),
]


def _parametros_section(ctx: dict) -> None:
    st.subheader("⚙️ Parámetros del Sistema")
    st.caption("Parámetros autorizados que controlan el comportamiento del sistema.")

    # Fetch current values
    params_stored = {p["clave"]: p for p in db.list_system_params()}

    with st.form("cfg_params_form"):
        values: dict[str, str] = {}
        for clave, label, default in _PARAMS_CATALOG:
            stored = params_stored.get(clave)
            current_val = stored["valor"] if stored and stored["valor"] is not None else default
            values[clave] = st.text_input(label, value=current_val, key=f"param_{clave}")

        p_submitted = st.form_submit_button("💾 Guardar parámetros")

    if p_submitted:
        try:
            for clave, label, _ in _PARAMS_CATALOG:
                valor = values[clave].strip()
                db.set_system_param(
                    clave=clave,
                    valor=valor,
                    descripcion=label,
                    usuario_rol=ctx["usuario_rol"],
                )
            db.log_audit(
                db.AUDIT_CONFIG,
                "Configuración",
                detalle="Parámetros del sistema actualizados",
                usuario_rol=ctx["usuario_rol"],
            )
        except Exception as exc:  # noqa: BLE001
            st.error(f"No se pudo guardar: {exc}")
        else:
            st.success("Parámetros guardados.")
            st.rerun()


